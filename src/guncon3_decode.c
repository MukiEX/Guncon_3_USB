bool guncon3_decode(const uint8_t d[15], const uint8_t key[8], uint8_t out[13]) {
  // All arithmetic is mod 256, as in the reference implementations
  uint8_t b_sum = (uint8_t)(((d[13] ^ d[12]) + d[11] + d[10] - d[9] - d[8]) ^ d[7]);
  uint8_t a_sum = (uint8_t)((((d[6] ^ b_sum) - d[5] - d[4]) ^ d[3]) + d[2] + d[1] - d[0]);
  if (a_sum != key[7]) return false;

  uint8_t ko = (uint8_t)((((((key[1] ^ key[2]) - key[3] - key[4]) ^ key[5]) + key[6] - key[7]) ^ d[14]) + 0x26);
  int key_offset = ko;   // decremented without wrap: table index stays within 26..319
  int key_index = 4;

  for (int x = 12; x >= 0; x--) {
    uint8_t byte = d[x];
    for (int y = 4; y > 1; y--) {
      key_offset--;
      uint8_t bkey = KEY_TABLE[key_offset + 0x41];
      uint8_t keyr = key[key_index];
      if (--key_index == 0) key_index = 7;
      switch (bkey & 3) {
        case 0:  byte = (uint8_t)(byte - bkey - keyr); break;
        case 1:  byte = (uint8_t)(byte + bkey + keyr); break;
        default: byte = (uint8_t)(byte ^ bkey ^ keyr); break;
      }
    }
    out[x] = byte;
  }
  return true;
}

