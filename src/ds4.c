// DualShock 4 output mode: each gun is a USB DS4 ("Wireless Controller", 054C:09CC).
//
// The 64-byte input report follows the real DS4 layout, so DS4-aware software (Steam,
// DS4Windows, Linux hid-playstation) reads it normally. DS4 sticks are only 8-bit, which is
// coarse for a light gun, so the HID descriptor also declares two 16-bit axes (Slider and
// Dial) carrying full-precision aim in bytes 48..51, padding on a real DS4. Descriptor-driven
// readers (Windows DirectInput / MAME) see them as two extra axes.
//
// Feature reports answered like GP2040-CE's PS4 mode: 0x02 calibration, 0x03 definition,
// 0x12 pairing info (MAC, unique per pad), 0xA3 firmware info.

#include <string.h>
#include "tusb.h"
#include "ds4.h"
#include "settings.h"

